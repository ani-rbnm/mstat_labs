# Generally required
import pandas as pd

# Plotting
import matplotlib
import seaborn as sns
import matplotlib.pyplot as plt

matplotlib.use("QtAgg")
sns.set_style("whitegrid")

########################################################################################################################
# 1. Data
########################################################################################################################

# Define file path
file = "Workshop 1 - Solution codes/Exercise 1.1/BuildingMaterials.xls"

# Load building materials data
series = pd.read_excel(
    file, sheet_name="Data", header=0, index_col=0, parse_dates=True
).squeeze()

########################################################################################################################
# 2. Time Plot
########################################################################################################################

# Create time plot
series.plot(
    color="red",
    title="Building materials production from 1986 to 2008",
    xlabel="Dates",
    ylabel="Production values",
)
plt.show()

