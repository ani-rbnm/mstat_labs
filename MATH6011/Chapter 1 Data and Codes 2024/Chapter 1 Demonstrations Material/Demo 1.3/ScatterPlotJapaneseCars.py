# Generally required
import pandas as pd

# Plotting
import seaborn as sns
import matplotlib.pyplot as plt

# matplotlib.use('Qt5Agg')
sns.set_style("whitegrid")

########################################################################################################################
# 1. Data
########################################################################################################################

# Define file path
file = "Chapter 1 Data and Codes 2024/Chapter 1 Demonstrations Material/Demo 1.3/JapaneseCars.xls"

# Load Japanese cars data
df = pd.read_excel(file, sheet_name="Data", header=0, dtype=float).squeeze()

########################################################################################################################
# 2. Scatter Plot
########################################################################################################################

# Create scatter plot
plt.scatter(df.Mileage, df.Price)

# Rename x-axis
plt.xlabel("Mileage (MPG)")

# Rename y-axis
plt.ylabel("Price (US$)")

# Set tile
plt.title("Price/Mileage Relationship for 19 Japanese cars")

plt.show()

