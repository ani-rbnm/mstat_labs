# Generally required
import pandas as pd

########################################################################################################################
# 1. Data
########################################################################################################################

# Define file path
file = "Chapter 1 Data and Codes 2024/Chapter 1 Demonstrations Material/Demo 1.4/JapaneseCars.xls"

# Load Japanese cars data
df = pd.read_excel(file, sheet_name='Data', header=0, dtype=float).squeeze()

########################################################################################################################
# 2. Correlation
########################################################################################################################

# generates correlation in a matrix format
correlation_matrix = df.corr()

# to extract the most important value
correlation_value = correlation_matrix.loc["Mileage", "Price"]

# Print correlation
print(correlation_value)

