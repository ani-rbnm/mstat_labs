# Generally required
import pandas as pd

# Plotting
import matplotlib
import seaborn as sns
import matplotlib.pyplot as plt
# matplotlib.use('Qt5Agg')
sns.set_style("whitegrid")

########################################################################################################################
# 1. Data
########################################################################################################################

# Define file path
file = "Chapter 4 Data and Codes 2024/Chapter 4 Demonstrations Material/Bank.xls"

# Load bank data set
df = pd.read_excel(file, sheet_name='Data3', header=0, dtype=float).squeeze()

########################################################################################################################
# 2. Correlation
########################################################################################################################

# Plotting the scatter plots of each variable against the other one
pd.plotting.scatter_matrix(df, figsize=(8, 8))
plt.show()

# Correlation matrix for all the variables, 2 by 2
CorrelationMatrix = df.corr()
print(CorrelationMatrix)
